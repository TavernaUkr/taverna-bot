/**
 * Перетворює "сирий" HTML-опис товару (з XML-фіда постачальника, напр.
 * `<br />`, `<p>`, `&amp;`) у безпечний текст для рендеру:
 *  - `<br>`, `<p>`, `<div>` -> переноси рядків;
 *  - решта HTML-тегів прибирається;
 *  - поширені HTML-сутності (&amp;, &quot; тощо) розкодовуються.
 *
 * Свідомо НЕ використовуємо `dangerouslySetInnerHTML`: без бібліотеки типу
 * DOMPurify самописна "санітизація" легко пропускає XSS (напр. через
 * `<img onerror=...>` в описі від постачальника). Оскільки описи товарів
 * фактично текстові (лише `<br />` для абзаців), безпечніше і достатньо
 * показати їх як звичайний текст зі збереженими переносами рядків
 * (в парі з CSS-класом `whitespace-pre-wrap` у `ProductDetail.tsx`).
 */
export function formatProductDescription(raw?: string | null): string {
  if (!raw) return "";

  return raw
    .replace(/\\n/g, "\n")
    // <br>, <br/>, <br />, <BR> -> перенос рядка
    .replace(/<br\s*\/?>/gi, "\n")
    // </p>, </div> -> абзац (подвійний перенос)
    .replace(/<\/(p|div)>/gi, "\n\n")
    // прибираємо всі інші HTML-теги (<b>, <span style="...">, <script> і т.д.)
    .replace(/<[^>]+>/g, "")
    // розкодовуємо найпоширеніші HTML-сутності
    .replace(/&nbsp;/gi, " ")
    .replace(/&amp;/gi, "&")
    .replace(/&quot;/gi, '"')
    .replace(/&#39;|&apos;/gi, "'")
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">")
    // прибираємо потрійні+ переноси рядків, що могли утворитись
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}
